/** A code's name in CAMEO's words, and its parent's where it is a four-digit code; null for a code it does not name. */
export function cameoNameOf(code: string): { name: string; parent: { code: string; name: string } | null } | null {
  const named = (c: string): string | null =>
    (Object.prototype.hasOwnProperty.call(CAMEO_NAMES, c) ? CAMEO_NAMES[c]
      : Object.prototype.hasOwnProperty.call(CAMEO_CONFLICT_NAMES, c) ? CAMEO_CONFLICT_NAMES[c] : null);
  const name = named(code);
  if (!name) return null;
  const parentCode = code.length === 4 ? code.slice(0, 3) : null;
  const parentName = parentCode ? named(parentCode) : null;
  return { name, parent: parentCode && parentName ? { code: parentCode, name: parentName } : null };
}
