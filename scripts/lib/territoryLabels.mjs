/**
 * Country names for the globe (decision K5, step 4: TS10–TS13,
 * docs/missions/01-architecture-decisions/territories.md): Natural Earth's own
 * name, label point, label rank and the zoom it first labels a country at, read
 * from the territory GeoJSON every baked part is cut from.
 *
 * Shared by scripts/label-territories.mjs, which writes the table, and the test
 * that reads the GeoJSON again and fails when the table is stale.
 */

/** Longer than this, a name is broken once, at the space nearest its middle. */
export const NAME_LINE_CHARS = 14;

/** A name as it is drawn: upper case, on one line, or two when it is long and has a space. */
export function nameLines(name) {
  const upper = name.toLocaleUpperCase('en');
  if (upper.length <= NAME_LINE_CHARS) return [upper];
  const middle = upper.length / 2;
  let best = -1;
  for (let i = 0; i < upper.length; i++) {
    if (upper[i] === ' ' && (best < 0 || Math.abs(i - middle) < Math.abs(best - middle))) best = i;
  }
  return best < 0 ? [upper] : [upper.slice(0, best), upper.slice(best + 1)];
}

const byRankThenZoomThenCode = (a, b) => a.rank - b.rank || a.minZoom - b.minZoom || (a.code < b.code ? -1 : a.code > b.code ? 1 : 0);

/** One row per territory, in the order names are placed: rank, then the zoom it labels at, then code. */
export function labelRows(collection) {
  return collection.features.map((feature) => {
    const p = feature.properties;
    return {
      code: p.ADM0_A3,
      name: p.NAME,
      lines: nameLines(p.NAME),
      lng: p.LABEL_X,
      lat: p.LABEL_Y,
      rank: p.LABELRANK,
      minZoom: p.MIN_LABEL,
      maxZoom: p.MAX_LABEL,
    };
  }).sort(byRankThenZoomThenCode);
}

const literal = (value) => JSON.stringify(value);

/** The module scripts/label-territories.mjs writes, as text, so the test can say when it is stale. */
export function labelModuleSource(rows) {
  const body = rows.map((r) => `  { code: ${literal(r.code)}, name: ${literal(r.name)}, lines: ${literal(r.lines)}, lng: ${r.lng}, lat: ${r.lat}, rank: ${r.rank}, minZoom: ${r.minZoom}, maxZoom: ${r.maxZoom} },`);
  return `/**
 * GENERATED by scripts/label-territories.mjs from the territory GeoJSON; do not edit.
 * Re-run it (npm run geo:labels) when the territories change; territoryLabels.test.ts
 * fails until then.
 *
 * Natural Earth's name for each territory, its label point, its label rank and the
 * zoom it first labels it at (decision K5, step 4). Names are Natural Earth's, which
 * show de facto control (TS12). maxZoom is kept and not applied (TS13).
 */
export interface TerritoryLabel {
  /** ADM0_A3, which every baked part carries as its countryCode. */
  code: string;
  /** NAME, Natural Earth's short map form ("Dem. Rep. Congo"). */
  name: string;
  /** As drawn: upper case, broken once past ${NAME_LINE_CHARS} characters at the space nearest the middle. */
  lines: readonly string[];
  /** LABEL_X and LABEL_Y, degrees. */
  lng: number;
  lat: number;
  /** LABELRANK: 2 for the giants, up to 7. */
  rank: number;
  /** MIN_LABEL: the web-map zoom Natural Earth first labels it at. */
  minZoom: number;
  /** MAX_LABEL: where its name would give way to its provinces'. */
  maxZoom: number;
}

/** Sorted by rank, then the zoom it labels at, then code: the order names are placed in. */
export const TERRITORY_LABELS: readonly TerritoryLabel[] = [
${body.join('\n')}
];
`;
}
